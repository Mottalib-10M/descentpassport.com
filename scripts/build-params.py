#!/usr/bin/env python3
"""Builds src/data/params-2026.json from the curated values below and the source lists of scripts/research/*.json.

Every figure here was read on the official page named by its `src` key on 2026-10-25 (scripts/research/<code>.json
keeps the exact quote). Run: python3 scripts/build-params.py
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
R = ROOT / 'scripts' / 'research'

sources = {}
for f in sorted(R.glob('*.json')):
    d = json.loads(f.read_text())
    if not isinstance(d, dict):
        continue
    for s in d.get('sources', []):
        k = s.get('key')
        if not k or not s.get('url', '').startswith('http'):
            continue
        sources.setdefault(k, {'url': s['url'], 'label': {'en': (s.get('title') or k).strip()}})

EXTRA = {
    'irs-physical-presence': ('https://www.irs.gov/individuals/international-taxpayers/foreign-earned-income-exclusion-physical-presence-test', 'IRS, Foreign earned income exclusion: physical presence test'),
    'ca-cdph-fees': ('https://www.cdph.ca.gov/Programs/CHSI/Pages/Vital-Records-Fees.aspx', 'California Department of Public Health, Vital Records fees (from January 1, 2026)'),
}
for k, (u, l) in EXTRA.items():
    sources.setdefault(k, {'url': u, 'label': {'en': l}})

C = json.loads((ROOT / 'scripts' / 'countries.json').read_text())

# Every src key used by a country must exist.
missing = []
def walk(x, path=''):
    if isinstance(x, dict):
        for k, v in x.items():
            if k == 'src' and isinstance(v, str) and v not in sources:
                missing.append(f'{path}.{k}={v}')
            walk(v, f'{path}.{k}')
    elif isinstance(x, list):
        for i, v in enumerate(x):
            walk(v, f'{path}[{i}]')
walk(C)

US = json.loads((ROOT / 'scripts' / 'us.json').read_text())
walk(US, 'us')
if missing:
    print('Unknown source keys:', *missing, sep='\n  ')
    sys.exit(1)

dual = []
for code, k in C.items():
    dual.append({'code': code, 'name': k['name'], 'status': k['dual']['status'], 'note': k['dual']['text'], 'descent': k['gens'], 'src': k['dual']['src'], 'page': f"/en/{k['slug']}/"})
DT = R / 'dual-table.json'
if DT.exists():
    rows = json.loads(DT.read_text())
    rows = rows.get('countries', rows) if isinstance(rows, dict) else rows
    for r in rows:
        if r.get('code') in C or not r.get('src_url', '').startswith('http'):
            continue
        sources.setdefault(r['src_key'], {'url': r['src_url'], 'label': {'en': r.get('src_title') or r['src_key']}})
        dual.append({'code': r['code'], 'name': r['name'], 'status': r['status'], 'note': r['note'], 'descent': r.get('descent', '') if r.get('descent_from_quoted_source') else '', 'src': r['src_key']})
dual.sort(key=lambda r: r['name'])

# Keep only the sources the site cites (pages, tools, country data): research notes list more.
used_text = ''.join(f.read_text() for f in (ROOT / 'src').rglob('*') if f.suffix in ('.ts', '.tsx', '.astro') and f.is_file())
used_text += json.dumps(C) + json.dumps(US)
used = {r['src'] for r in dual} | {k for k in sources if f"'{k}'" in used_text or f'"{k}"' in used_text}
sources = {k: v for k, v in sources.items() if k in used}

out = {
    '_lisezmoi': 'Generated by scripts/build-params.py from scripts/countries.json, scripts/us.json and the source lists of scripts/research/*.json. Edit those files, never this one.',
    'year': 2026,
    'retrieved_at': '2026-10-25',
    'valid_from': '2026-10-25',
    'valid_to': '2026-12-31',
    'sources': dict(sorted(sources.items())),
    'countries': C,
    'us': US,
    'dualTable': dual,
}
(ROOT / 'src' / 'data' / 'params-2026.json').write_text(json.dumps(out, ensure_ascii=False, indent=1) + '\n')
print(f"params-2026.json: {len(sources)} sources, {len(C)} countries")
